const fs = require('fs')
const path = require('path')

console.log('Syncing real component source code into registry sources map...')

const rootDir = path.resolve(__dirname, '..')
const registryDir = path.join(rootDir, 'registry')
const destMapPath = path.join(rootDir, 'src', 'registry', 'componentSources.ts')

const sources = {}

const categories = fs.readdirSync(registryDir).filter(f => fs.statSync(path.join(registryDir, f)).isDirectory())

categories.forEach(cat => {
  const catDir = path.join(registryDir, cat)
  const components = fs.readdirSync(catDir).filter(f => fs.statSync(path.join(catDir, f)).isDirectory())

  components.forEach(comp => {
    const srcPath = path.join(catDir, comp, `${comp}.tsx`)
    if (fs.existsSync(srcPath)) {
      sources[comp] = fs.readFileSync(srcPath, 'utf8')
    }
  })
})

const fileContent = `// Automatically generated by scripts/sync-component-sources.cjs - DO NOT EDIT MANUALLY
export const COMPONENT_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)}
`

fs.writeFileSync(destMapPath, fileContent)
console.log(`Synced ${Object.keys(sources).length} full component sources to src/registry/componentSources.ts!`)
